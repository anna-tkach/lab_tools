#!/bin/bash
# _tools/env_runner/run.sh
#
# Що робить - запускає безпечне середовище для виконання із обмеженими правами і доступами.
# Навіщо - запускати агентів! claude і все інше має запускатися через нього!
#
# Використання:
#   run.sh --method=<method> --profile=<path> --tests=<path> -- <command> [args...]
#
# Прапорці:
#   --method=   метод ізоляції. Підтримувані метод: [apple-sandbox].
#   --profile=  шлях до конфігу цього методу (для apple-sandbox — .sb-файл)
#   --tests=    шлях до tests-файлу для permission-inside-selfcheck.sh. Файл містить набір команд для переврки куди є доступ а куди нема.
#
# Все, що йде ПІСЛЯ "--", вважається командою для фінальної сесії (разом з її
# аргументами) і передається далі як є, без розбиття чи екранування рядка —
# наприклад: -- claude --model sonnet
#
# Повертає:
#   0 — сесія завершилась нормально
#   не 0 — перевірка не пройдена, сесія не запускалась

METHOD=""
PROFILE=""
TESTS_FILE=""

# розбираємо прапорці до тих пір, поки не зустрінемо "--" або кінець аргументів
while [ "$#" -gt 0 ]; do
  case "$1" in
    --method=*)
      # "${1#--method=}" — відрізає префікс "--method=" від аргумента,
      # лишаючи тільки значення після знака "="
      METHOD="${1#--method=}"
      shift
      ;;
    --profile=*)
      PROFILE="${1#--profile=}"
      shift
      ;;
    --tests=*)
      TESTS_FILE="${1#--tests=}"
      shift
      ;;
    --)
      shift
      break
      ;;
    *)
      echo "Невідомий прапорець: $1"
      exit 1
      ;;
  esac
done

FINAL_COMMAND=("$@")

# перевіряємо, що всі обов'язкові прапорці задані (не порожні) і що після "--"
# реально передали хоч якусь команду — інакше немає сенсу продовжувати
# "-z" — перевірка "рядок порожній", "${#FINAL_COMMAND[@]}" — кількість елементів масиву
if [ -z "$METHOD" ] || [ -z "$PROFILE" ] || [ -z "$TESTS_FILE" ] || [ "${#FINAL_COMMAND[@]}" -eq 0 ]; then
  echo "Використання: run.sh --method=<method> --profile=<path> --tests=<path> -- <command> [args...]"
  exit 1
fi

# перевіряємо, що файл профілю реально існує за вказаним шляхом
if [ ! -f "$PROFILE" ]; then
  echo "Файл профілю не знайдено: $PROFILE"
  exit 1
fi

# перевіряємо, що файл із тестами реально існує за вказаним шляхом
if [ ! -f "$TESTS_FILE" ]; then
  echo "Файл tests не знайдено: $TESTS_FILE"
  exit 1
fi

# формуємо шлях до конкретної реалізації методу — наприклад, для METHOD="apple-sandbox"
# це буде "impl/apple-sandbox-run.sh"; "$(dirname "$0")" — тека, де лежить сам run.sh,
# так шлях працює незалежно від того, звідки run.sh запущено
IMPL_SCRIPT="$(dirname "$0")/impl/${METHOD}/${METHOD}-run.sh"

# перевіряємо, що файл реалізації для вказаного методу реально існує —
# захист від одруку в назві методу (наприклад "aple-sandbox") чи ще не написаної реалізації
if [ ! -f "$IMPL_SCRIPT" ]; then
  echo "Невідомий метод '$METHOD': не знайдено $IMPL_SCRIPT"
  exit 1
fi

# викликаємо знайдену реалізацію, передаючи їй profile, tests-файл і команду —
# "${FINAL_COMMAND[@]}" розкриває масив як окремі аргументи (не один злитий рядок)
"$IMPL_SCRIPT" "$PROFILE" "$TESTS_FILE" "${FINAL_COMMAND[@]}"